// ============================================================================
// Agent types
// ============================================================================

/** Supported AI agent CLI types */
export type AgentType = 'cursor' | 'github-copilot' | 'claude-code'

/** Status of an agent session */
export type AgentSessionStatus = 'starting' | 'running' | 'stopped' | 'error'

/** Configuration for a specific agent type */
export interface AgentConfig {
  /** The CLI command to spawn the agent */
  command: string
  /** Arguments to pass to the command */
  args?: string[]
  /** Function to generate the process attach command */
  processAttachCommand: (processPath: string) => string
  /** Whether this agent type is currently available */
  available: boolean
  /** Display name for the UI */
  displayName: string
}

/** An active agent CLI session */
export interface AgentSession {
  /** Unique identifier for this session */
  id: string
  /** The type of agent CLI */
  agentType: AgentType
  /** ID of the attached agentic process (if any) */
  attachedProcessId: ProcessId | null
  /** Path to the attached agentic process directory (if any) */
  attachedProcessPath: string | null
  /** Current status of the session */
  status: AgentSessionStatus
  /** When the session was created */
  createdAt: ISOTimestamp
  /** Working directory for the agent */
  workingDirectory: string
}

