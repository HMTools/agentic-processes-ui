// Types based on the agentic-processes framework

// ============================================================================
// Shared utility types (matching framework)
// ============================================================================

/** UUID identifier for a process instance */
export type ProcessId = string

/** UUID identifier for a step within a process */
export type StepId = string

/** ISO 8601 timestamp string */
export type ISOTimestamp = string

/** Absolute path to a process directory under ~/.claude/agentic-processes/ */
export type ProcessPath = string

/** Reference to a step definition */
export type StepRef = string

/** Sync point for child process coordination (references a StepId) */
export type SyncPoint = StepId

// ============================================================================
// Status types
// ============================================================================

export type ProcessStatus = 'running' | 'completed' | 'failed' | 'paused'

export type StepStatus = 'pending' | 'in_progress' | 'completed' | 'skipped' | 'awaiting_approval'

// ============================================================================
// Process instance types
// ============================================================================

export interface ProcessMetadata {
  template: string
  templateCategory?: string
  created: ISOTimestamp
  lastUpdated: ISOTimestamp
  projectPaths?: string[]
  /** @deprecated Use projectPaths instead */
  projectPath?: string
  processPath?: ProcessPath
  /** Claude Code session ID — used by hooks and for session migration */
  sessionId?: string
}

export interface ProcessCurrentState {
  activeStepId: StepId
  activeStepName: string
  actionSummary: string
  actionDetails?: string
}

/**
 * An option presented to the user for selection during step interaction.
 * Used when a step needs user input beyond simple approval.
 */
export interface InteractionOption {
  /** Unique identifier for this option */
  id: string
  /** Display label for this option in the UI */
  label: string
  /** Optional longer description shown as tooltip or help text */
  description?: string
  /** Whether this option should be pre-selected/highlighted as default */
  isDefault?: boolean
}

/**
 * The options shape used within a PendingInteractionFile.
 * Kept as a named interface for reuse and clarity.
 */
export interface PendingInteraction {
  /** Options for user selection, dynamically generated by the agent */
  options: InteractionOption[]
}

/**
 * Represents the content of a pending-interaction.json file in a process folder.
 * Created by the agent when user input is needed, deleted when user responds.
 * File absence = no pending interaction.
 */
export interface PendingInteractionFile {
  type: 'pending-interaction'
  options: InteractionOption[]
}

export interface ProcessStep {
  id: StepId
  number: number
  name: string
  status: StepStatus
  stepRef: StepRef
  startedAt?: ISOTimestamp
  completedAt?: ISOTimestamp
  approvalRequired?: boolean
  approved?: boolean
}

export interface ChildProcessRef {
  id: ProcessId
  name: string
  status: ProcessStatus
  spawnedAtStep: StepId
  syncPoint: SyncPoint
  processPath: ProcessPath
}

export interface ParentProcessRef {
  id: ProcessId
  name: string
  processPath: ProcessPath
  returnToStep: StepId
}

export interface SubProcessState {
  parentProcess: ParentProcessRef | null
  childProcesses: ChildProcessRef[]
  nextSyncPoint?: StepId
}

export interface ProcessInstance {
  type: 'process-instance'
  id: ProcessId
  name: string
  metadata: ProcessMetadata
  status: ProcessStatus
  parameters: Record<string, string>
  currentState: ProcessCurrentState
  steps: ProcessStep[]
  subProcessState?: SubProcessState
}

